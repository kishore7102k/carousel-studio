// Bundles brand-pack/default into src/brand/default-pack.ts (OFL fonts, safe to commit).
// Run after editing brand-pack/default:  npm run brand:default
import { readFileSync, writeFileSync, readdirSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dir = join(root, 'brand-pack', 'default');
const fonts = readdirSync(join(dir, 'fonts')).filter(f => f.endsWith('.woff2')).map(file => {
  const [, fam, weight] = /^(.+)-(\d+)\.woff2$/.exec(file);
  return { family: { PlusJakartaSans: 'Plus Jakarta Sans', JetBrainsMono: 'JetBrains Mono' }[fam] ?? fam, weight, data: readFileSync(join(dir, 'fonts', file)).toString('base64') };
});
const pack = {
  name: 'Carousel Studio',
  handle: '@yourhandle',
  labelPrefix: 'Tip',
  readme: readFileSync(join(dir, 'README.md'), 'utf8'),
  tokens: JSON.parse(readFileSync(join(dir, 'tokens.json'), 'utf8')),
  fonts,
  roles: {},
};
mkdirSync(join(root, 'src', 'brand'), { recursive: true });
writeFileSync(join(root, 'src', 'brand', 'default-pack.ts'), `// GENERATED by scripts/build-default-brand.mjs. Fonts: SIL Open Font License (see brand-pack/default/fonts).
import type { BrandPack } from '@/lib/brand';
export const DEFAULT_PACK: BrandPack = ${JSON.stringify(pack)};
`);
console.log(`default brand pack: ${fonts.map(f => `${f.family} ${f.weight}`).join(', ')}`);
